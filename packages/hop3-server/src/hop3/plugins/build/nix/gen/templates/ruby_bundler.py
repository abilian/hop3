"""ruby-bundler template.

For Ruby applications using Bundler. ``pkgs.bundlerEnv`` builds the gem set
from a committed ``Gemfile`` / ``Gemfile.lock`` / ``gemset.nix`` triple (the
last generated by ``bundix`` — the Ruby analogue of ``buildGoModule``'s
``vendorHash``), and the app is wrapped with a startup script.

Two shapes are supported:

- **Packaged app** — ``[nix].url`` names a release tarball. The source is
  fetched and hash-pinned, the whole tree is installed, and the recipe's
  ``Gemfile``/``gemset.nix`` describe its dependencies. This is how a real
  application (Rails or otherwise) is packaged.
- **Local app** — no ``url``; the recipe directory *is* the application. Used
  by the small fixtures.

Either way the generated ``hop3.nix`` must live in the recipe directory, since
``gemdir = ./.`` resolves the gem triple relative to it.

Rails specifics stay in the *recipe*, not here: a Rails app writes into its own
tree (generated ``config/database.yml``, secret token, ``tmp/``, ``log/``),
which the read-only Nix store forbids, so it sets ``writable-home-at-runtime``
and expresses its config file, migration and boot command through the shared
``[nix].config-files`` / ``pre-exec`` / ``exec-args`` fields. Generating gems
with ``force_ruby_platform`` keeps every gem built from source rather than a
precompiled binary.

Example apps: redmine (Rails, packaged); sinatra-hello, rack-hello (local).
"""

from __future__ import annotations

from dataclasses import replace

from hop3.plugins.build.nix.gen.spec import AppSpec
from hop3.plugins.build.nix.gen.templates.base import (
    PINNED_NIXPKGS_HEADER,
    ReproTier,
    build_writable_home_prelude,
    format_nix_env_attrs,
    format_paths_json,
    format_runtime_env_json,
    format_wrapper_body,
)


class RubyBundlerTemplate:
    name = "ruby-bundler"
    tier = ReproTier.SOURCE

    def generate(self, spec: AppSpec) -> str:
        if spec.exec_target is None:
            raise ValueError("ruby-bundler requires exec_target")

        ruby_pkg = spec.runtime_package or "ruby_3_3"

        # A packaged app fetches a pinned release tarball; a local app is the
        # recipe directory itself.
        if spec.source.url:
            binding = f"{spec.pname.replace('-', '_')}_src"
            source_nix = spec.source.as_nix(binding) + "\n"
            src_attr = binding
            # The gem set was resolved from the recipe's Gemfile, but the app
            # runs with its own tree as the working directory — so bundler would
            # resolve the *tarball's* Gemfile, find it disagrees with the
            # lockfile the gems came from, and refuse to boot
            # ("ensure_equivalent_gemfile_and_lockfile: Some dependencies were
            # deleted"). Install the pair the gem set was built from.
            gemfile_install = (
                "\n      cp ${./Gemfile} $out/app/Gemfile"
                "\n      cp ${./Gemfile.lock} $out/app/Gemfile.lock"
            )
        else:
            source_nix = ""
            src_attr = "./."
            gemfile_install = ""

        prelude_parts: list[str] = []
        if spec.writable_home_at_runtime:
            # Rails-class apps write inside their own tree and resolve paths
            # relative to the working directory, so cd into the writable copy.
            prelude_parts.append(
                build_writable_home_prelude(
                    spec.pname,
                    "APPDIR",
                    spec.writable_home_env_var,
                    cd_into=True,
                )
            )
        # Put the gem set's binaries on PATH so pre-exec steps can invoke
        # `rake`, `rails` etc. directly instead of knowing the store path.
        prelude_parts.append('export PATH="GEMSBIN:$PATH"')
        if spec.runtime_prelude:
            prelude_parts.append(spec.runtime_prelude)
        spec = replace(spec, runtime_prelude="\n\n".join(prelude_parts))

        exec_args = " " + " ".join(spec.exec_args) if spec.exec_args else ""
        exec_line = f"GEMSBIN/{spec.exec_target}{exec_args}"
        wrapper_body = format_wrapper_body(spec, exec_line)

        runtime_env_json = format_runtime_env_json(spec.runtime_env)
        nix_env_attrs = format_nix_env_attrs(spec.runtime_env)
        paths_json = format_paths_json(spec.extra_paths)

        return f"""# hop3.nix - Nix expression for {spec.pname}
#
# GENERATED from template 'ruby-bundler' by hop3-nix-gen.
# Gems are built from a committed Gemfile.lock + gemset.nix (bundix), so the
# dependency set is pinned and every gem is compiled from source.
#
# Run 'hop3 nix eject {spec.pname}' to materialize for customization.

{PINNED_NIXPKGS_HEADER}

let
  ruby = pkgs.{ruby_pkg};
  version = "{spec.version}";

{source_nix}
  # bundix-generated gemset.nix pins each gem by hash; bundlerEnv compiles the
  # native extensions (nokogiri, pg, …) in the sandbox.
  gems = pkgs.bundlerEnv {{
    name = "{spec.pname}-gems";
    inherit ruby;
    gemdir = ./.;
  }};

  app = pkgs.stdenv.mkDerivation {{
    pname = "{spec.pname}";
    inherit version;
    meta.description = "{spec.description}";

    src = {src_attr};

    buildInputs = [ ruby gems ];

    dontConfigure = true;
    dontBuild = true;

    installPhase = ''
      mkdir -p $out/app $out/bin $out/hop3
      cp -r . $out/app/{gemfile_install}

      cat > $out/bin/{spec.pname} << 'WRAPPER'
{wrapper_body}
WRAPPER
      sed -i "s|GEMSBIN|${{gems}}/bin|g" $out/bin/{spec.pname}
      sed -i "s|APPDIR|$out/app|g" $out/bin/{spec.pname}
      chmod +x $out/bin/{spec.pname}

      cat > $out/hop3/runtime.json << EOF
{{
  "workers": {{
    "web": "$out/bin/{spec.pname}"
  }},
  "env": {{
{runtime_env_json}
  }},
  "path": [
    {paths_json}
  ]
}}
EOF
    '';
  }};

in
{{
  package = app;

  env = {{{nix_env_attrs}}};
}}
"""
