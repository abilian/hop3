def _is_multiline_import(stripped: str) -> bool:
    """Check if an import statement spans multiple lines."""
    return "(" in stripped and ")" not in stripped


def _should_skip_import(stripped: str) -> bool:
    """Check if an import should be skipped (relative or future imports)."""
    return stripped.startswith("from .") or "from __future__" in stripped


def _extract_module_name(stripped: str) -> str | None:
    """Extract module name from an import statement."""
    if stripped.startswith("import "):
        match = re.match(r"import\s+([\w.]+)", stripped)
        return match.group(1) if match else None
    if stripped.startswith("from "):
        match = re.match(r"from\s+([\w.]+)\s+import", stripped)
        return match.group(1) if match else None
    return None


def extract_imports(source: str) -> tuple[set[str], str]:
    """Extract import statements from source code.

    Returns:
        Tuple of (set of import names, source with imports removed)
    """
    imports: set[str] = set()
    lines = source.split("\n")
    new_lines: list[str] = []
    in_multiline_import = False

    for line in lines:
        stripped = line.strip()

        # Skip empty lines at the start (before first non-import)
        if not stripped and not new_lines and not in_multiline_import:
            continue

        # Handle continuation of multi-line imports
        if in_multiline_import:
            if ")" in stripped:
                in_multiline_import = False
            continue

        # Check for import statements
        if stripped.startswith(("import ", "from ")):
            is_multiline = _is_multiline_import(stripped)

            if _should_skip_import(stripped):
                if is_multiline:
                    in_multiline_import = True
                continue

            module_name = _extract_module_name(stripped)
            if module_name:
                imports.add(module_name)

            if is_multiline:
                in_multiline_import = True
            continue

        new_lines.append(line)

    return imports, "\n".join(new_lines)


def _skip_leading_whitespace_and_comments(lines: list[str], start: int) -> int:
    """Skip leading whitespace and comment lines, return new index."""
    i = start
    while i < len(lines):
        stripped = lines[i].strip()
        if stripped and not stripped.startswith("#"):
            break
        i += 1
    return i


def _skip_module_docstring(lines: list[str], start: int) -> int:
    """Skip module docstring if present, return new index."""
    if start >= len(lines):
        return start

    stripped = lines[start].strip()
    if not (stripped.startswith(('"""', "'''"))):
        return start

    quote = stripped[:3]
    # Single-line docstring like """text"""
    if stripped.count(quote) >= 2 and len(stripped) > 3:
        return start + 1

    # Multi-line docstring - find the end
    i = start + 1
    while i < len(lines):
        if quote in lines[i]:
            return i + 1
        i += 1
    return i


def extract_code_body(source: str) -> str:
    """Extract the main code body, removing module docstrings and boilerplate.

    Only removes:
    - Leading comments and whitespace
    - Module-level docstring (first triple-quoted string at column 0)
    - if __name__ == "__main__" block at the end
    """
    lines = source.split("\n")
    n = len(lines)

    # Skip leading content
    i = _skip_leading_whitespace_and_comments(lines, 0)
    i = _skip_module_docstring(lines, i)

    # Skip any blank lines after docstring
    while i < n and not lines[i].strip():
        i += 1

    # Collect remaining lines until if __name__ block
    new_lines = []
    while i < n:
        stripped = lines[i].strip()
        if stripped.startswith('if __name__ == "__main__"'):
            break
        new_lines.append(lines[i])
        i += 1

    return "\n".join(new_lines)


def _top_level_names(code: str) -> list[str]:
    """Return top-level function/class/assignment names defined in code.

    Used by the bundler to detect name collisions across modules.
    Parses with ``ast``; on syntax error returns an empty list (the
    bundler will fail later with a clearer error).
    """
    import ast  # noqa: PLC0415

    try:
        tree = ast.parse(code)
    except SyntaxError:
        return []

    names: list[str] = []
    for node in tree.body:
        if isinstance(node, (ast.FunctionDef, ast.AsyncFunctionDef, ast.ClassDef)):
            # Skip @overload-decorated stubs — they're intentional
            # duplicates that typing.overload merges at runtime.
            if any(
                (isinstance(d, ast.Name) and d.id == "overload")
                or (isinstance(d, ast.Attribute) and d.attr == "overload")
                for d in node.decorator_list
            ):
                continue
            names.append(node.name)
        elif isinstance(node, ast.Assign):
            for target in node.targets:
                if isinstance(target, ast.Name):
                    names.append(target.id)
    return names


def _collect_import_statements(source: str) -> set[str]:
    """Full, normalized stdlib-candidate import statements found in ``source``.

    Uses ``ast`` so multi-line and conditional (e.g. ``if TYPE_CHECKING:``)
    imports are captured correctly, and — crucially — so the imported *symbols*
    are preserved verbatim. This is what makes ``from typing import TypedDict``
    survive bundling: the old line-based path reduced it to the module name
    ``typing`` and re-emitted a bare ``import typing``, dropping ``TypedDict``
    unless it happened to be on a hand-maintained allowlist. A missed symbol
    then surfaced only as a ``NameError`` at install time (the bundle parses and
    byte-compiles fine — an undefined base class is a runtime error).

    Relative imports and ``__future__`` are skipped: relative code is inlined,
    and ``from __future__ import annotations`` already lives in the header.
    """
    import ast  # noqa: PLC0415

    try:
        tree = ast.parse(source)
    except SyntaxError:
        return set()

    statements: set[str] = set()
    for node in ast.walk(tree):
        if isinstance(node, ast.Import):
            for alias in node.names:
                suffix = f" as {alias.asname}" if alias.asname else ""
                statements.add(f"import {alias.name}{suffix}")
        elif isinstance(node, ast.ImportFrom):
            if node.level or node.module in {None, "__future__"}:
                continue
            names = ", ".join(
                a.name + (f" as {a.asname}" if a.asname else "") for a in node.names
            )
            statements.add(f"from {node.module} import {names}")
    return statements


def process_module(filepath: Path) -> tuple[set[str], str]:
    """Process a module file.

    Returns:
        Tuple of (full import statements, code body). The statements are
        normalized stdlib-candidate imports (see ``_collect_import_statements``);
        the body has its import lines stripped and is ready to inline.
    """
    source = filepath.read_text()

    # Strip import lines from the body (the returned module-name set is unused
    # here — emission uses the symbol-preserving statements collected below).
    _module_names, source_no_imports = extract_imports(source)

    # Extract code body
    code = extract_code_body(source_no_imports)

    return _collect_import_statements(source), code


