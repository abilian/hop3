def bundle_installer(installer_type: str) -> str:
    """Bundle an installer into a single file.

    Args:
        installer_type: 'cli' or 'server'

    Returns:
        The bundled source code
    """
    if installer_type == "cli":
        modules = CLI_MODULES
        description = CLI_DESCRIPTION
        usage = CLI_USAGE
    else:
        modules = SERVER_MODULES
        description = SERVER_DESCRIPTION
        usage = SERVER_USAGE

    # Collect imports and code from all modules
    all_imports: set[str] = set()
    code_sections: list[str] = []

    # Track top-level names so we can detect collisions: bundling
    # concatenates modules at module scope, so two modules defining
    # the same top-level function/class silently shadow each other
    # (last one wins) and the bug only surfaces at runtime.
    seen_names: dict[str, str] = {}

    for module_path in modules:
        filepath = SRC_DIR / module_path
        if not filepath.exists():
            msg = f"Module not found: {filepath}"
            raise FileNotFoundError(msg)

        imports, code = process_module(filepath)
        all_imports.update(imports)

        for name in _top_level_names(code):
            if name.startswith("_") and not name.startswith("__"):
                # Single-leading-underscore names are conventional
                # private helpers; collisions on those still bite,
                # but accept aliases like ``_has_systemd = has_systemd``
                # which intentionally re-export the shared helper.
                if code.find(f"{name} = ") != -1:
                    continue
            if name in seen_names:
                msg = (
                    f"Bundler name collision: '{name}' defined in both "
                    f"{seen_names[name]} and {module_path}. Move the "
                    "shared definition to common.py and import it."
                )
                raise ValueError(msg)
            seen_names[name] = module_path

        # Add section header
        section_name = module_path.replace("/", ".").replace(".py", "")
        code_sections.append(
            f"\n# {'=' * 77}\n# Module: {section_name}\n# {'=' * 77}\n"
        )
        code_sections.append(code)

    # Generate header
    header = HEADER_TEMPLATE.format(
        description=description,
        usage=usage,
        date=datetime.now().strftime("%Y-%m-%d %H:%M:%S"),
    )

    # Generate import block (stdlib only), preserving full statements verbatim
    # so imported symbols survive — no hand-maintained allowlist to drift out of
    # sync with the code. Non-stdlib imports are dropped (their code is inlined).
    import_lines = [
        stmt
        for stmt in sorted(all_imports)
        if (module := _extract_module_name(stmt)) and is_stdlib_module(module)
    ]

    import_block = "\n".join(import_lines) + "\n"

    # Combine everything
    parts = [header, import_block]
    parts.extend(code_sections)

    # Add main block
    parts.append(
        """

# =============================================================================
# Entry Point
# =============================================================================

if __name__ == "__main__":
    try:
        sys.exit(main())
    except KeyboardInterrupt:
        print("\\n\\nInstallation cancelled.")
        sys.exit(130)
    except Exception as e:
        print(f"\\n{Colors.RED}Error:{Colors.RESET} {e}", file=sys.stderr)
        sys.exit(1)
"""
    )

    return "\n".join(parts)


def validate_bundle(source: str) -> bool:
    """Validate that the bundled source is valid Python.

    Returns:
        True if valid, False otherwise
    """
    try:
        ast.parse(source)
        return True
    except SyntaxError as e:
        print(f"Syntax error in bundled source: {e}", file=sys.stderr)
        return False


