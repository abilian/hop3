def _process_is_alive(pid_text: str) -> bool:
    """
    Whether the process that created a container is still running.

    Signal 0 performs the permission and existence checks without delivering
    anything. A PermissionError means the pid exists under another user, which
    still counts as alive. A recycled pid reads as alive and the conflict is
    reported instead of reclaimed — erring toward the older, manual behaviour,
    which is the safe direction to be wrong in.
    """
    try:
        os.kill(int(pid_text), 0)
    except (ProcessLookupError, ValueError):
        return False
    except PermissionError:
        return True
    return True


class DockerDeployBackend(DeployBackend):
    """
    Backend for deploying to local Docker containers.

    This backend builds a Docker image using a Dockerfile, leveraging
    Docker's layer caching for fast rebuilds. The image is built fresh
    each time, but Docker caches unchanged layers so subsequent builds
    are nearly instant if nothing changed.
    """

    name = "docker"

    # Image name for built test image
    TEST_IMAGE = "hop3-test:latest"

    def __init__(self, config: DeployConfig) -> None:
        # Belt-and-suspenders interlock: this backend embeds a known JWT
        # signing key in its supervisor config (see E2E_TEST_SECRET_KEY).
        # Refuse to construct the backend if MODE=production so the key
        # can never reach a production-shaped deploy by accident.
        if os.environ.get("MODE", "").strip().lower() in {"production", "prod"}:
            msg = (
                "DockerDeployBackend is a developer-only deploy backend with a "
                "hardcoded E2E test signing key; it must not be used with "
                "MODE=production. Use the SSH backend or hop3-install instead."
            )
            raise RuntimeError(msg)

        super().__init__(config)
        self.container_name = config.docker_container
        self.image = self.TEST_IMAGE
        self._dockerfile_path = self._find_dockerfile()

    def _find_dockerfile(self) -> Path | None:
        """Find the Dockerfile for building the test image."""
        # Look for Dockerfile in known locations
        possible_paths = [
            self.config.project_root
            / "packages"
            / "hop3-installer"
            / "docker"
            / "Dockerfile.base",
            Path(__file__).parent.parent.parent.parent / "docker" / "Dockerfile.base",
        ]
        for path in possible_paths:
            if path.exists():
                return path
        return None

    def _build_image(self) -> bool:
        """
        Build the Docker image using docker build.

        Docker automatically uses layer caching, so unchanged layers
        are reused and rebuilds are fast.
        """
        if not self._dockerfile_path:
            print(
                "  ✗ Docker deploy can't build the test image: Dockerfile.base is "
                "missing from packages/hop3-installer/docker/; run from a hop3 "
                "checkout"
            )
            return False

        print("  → Building Docker image (using layer cache)...")
        print(f"    Dockerfile: {self._dockerfile_path}")

        build_cmd = [
            "docker",
            "build",
            "-f",
            str(self._dockerfile_path),
            "-t",
            self.TEST_IMAGE,
            str(self.config.project_root),
        ]

        result = subprocess.run(
            build_cmd,
            capture_output=False,  # Show build output
            check=False,
        )

        if result.returncode != 0:
            print(
                f"  ✗ Docker build failed (exit code {result.returncode}); "
                "the build output above names the failing step"
            )
            return False

        print(f"  ✓ Image built: {self.TEST_IMAGE}")
        return True

    def _docker_unavailable_reason(self) -> str | None:
        """Why ``docker info`` fails, or None when Docker answers."""
        try:
            result = subprocess.run(
                ["docker", "info"],
                capture_output=True,
                text=True,
                check=False,
            )
        except FileNotFoundError:
            return "no `docker` command on PATH"
        if result.returncode == 0:
            return None
        # The CLI names the cause (daemon down, context not found, permission
        # denied); a bare "not available" sent people to check the daemon when
        # the fault was their DOCKER_CONFIG.
        lines = [line for line in result.stderr.splitlines() if line.strip()]
        return lines[-1].strip() if lines else f"docker info exited {result.returncode}"

    def _container_exists(self) -> bool:
        """Check if the container exists."""
        result = subprocess.run(
            ["docker", "ps", "-a", "--filter", f"name=^{self.container_name}$", "-q"],
            capture_output=True,
            text=True,
            check=False,
        )
        return bool(result.stdout.strip())

    def _container_running(self) -> bool:
        """Check if the container is running."""
        result = subprocess.run(
            ["docker", "ps", "--filter", f"name=^{self.container_name}$", "-q"],
            capture_output=True,
            text=True,
            check=False,
        )
        return bool(result.stdout.strip())

    def _running_image(self) -> str | None:
        """The image the running container was created from, if it can be read."""
        result = subprocess.run(
            [
                "docker",
                "inspect",
                self.container_name,
                "--format",
                "{{.Config.Image}}",
            ],
            capture_output=True,
            text=True,
            check=False,
        )
        return result.stdout.strip() or None

    def _remove_container(self) -> None:
        """Remove the container if it exists."""
        subprocess.run(
            ["docker", "rm", "-f", self.container_name],
            capture_output=True,
            check=False,
        )

    def _reclaim_orphans(self) -> list[str]:
        """
        Remove the containers this tool created from here whose run is gone.

        A run killed by Ctrl-C, a timeout or an OOM cannot tear its own
        container down, and the container goes on using the Docker host's
        memory and disk. Per the project's own rule, a leftover is a platform
        bug, not something to tell the operator to go fix.

        Only containers carrying this backend's labels are ever touched, only
        those created from this machine (a pid means nothing on another), and
        only when the process that created them is gone: a live run's container
        is somebody's work in progress. Unlabelled containers (someone else's,
        or one from an older build) are left alone too.

        Returns the names reclaimed.
        """
        listed = subprocess.run(
            [
                "docker",
                "ps",
                "-a",
                "--filter",
                f"label={MARKER_LABEL}",
                "--filter",
                f"label={OWNER_HOST_LABEL}={socket.gethostname()}",
                "--format",
                "{{.Names}}",
            ],
            capture_output=True,
            text=True,
            check=True,
        )
        reclaimed: list[str] = []
        for name in listed.stdout.split():
            owner = self._container_label(name, OWNER_LABEL)
            if owner is None or _process_is_alive(owner):
                continue  # somebody is still using it
            print(
                f"  → Reclaiming '{name}': it belongs to hop3 run pid {owner}, "
                "which is no longer running (a killed run cannot clean up "
                "after itself)."
            )
            subprocess.run(
                ["docker", "rm", "-f", name], capture_output=True, check=False
            )
            reclaimed.append(name)
        return reclaimed

    def _container_label(self, name: str, label: str) -> str | None:
        """Return a label's value, or None if absent or the container is gone."""
        result = subprocess.run(
            [
                "docker",
                "inspect",
                "-f",
                f'{{{{index .Config.Labels "{label}"}}}}',
                name,
            ],
            capture_output=True,
            text=True,
            check=False,
        )
        if result.returncode != 0:
            return None
        value = result.stdout.strip()
        # `docker inspect` prints "<no value>" for a label that is not set.
        return value if value and value != "<no value>" else None

    def _start_container(self) -> bool:
        """
        Start a new Docker container.

        Returns:
            True if container started successfully, False otherwise.
        """
        print(f"  → Starting container from {self.image}...")
        run_result = subprocess.run(
            [
                "docker",
                "run",
                "-d",
                # A real init as PID 1, so exited children get reaped.
                #
                # PID 1 was `sleep infinity`, which never calls wait(). Anything
                # that forked a helper and waited for it to disappear then hung
                # on a zombie: mysql-server-8.0's postinst starts a temporary
                # mysqld, shuts it down cleanly, and polls for the pid to go —
                # the pid stayed, so it reported "Unable to shut down server",
                # dpkg failed, and the whole install died three steps later
                # under an unrelated error about apt-utils. Any package whose
                # postinst does the same would have hit it.
                "--init",
                # rootd manages the host firewall through nftables — it opens
                # each app's fixed [[ports]] in the `inet hop3` table. That needs
                # CAP_NET_ADMIN, which a container does not get by default.
                #
                # This was invisible while `nftables` was missing from the
                # installer's package list: with no `nft` binary, rootd skipped
                # reconciliation and started. Installing the package made it try,
                # and `nft add table inet hop3` returned "Operation not
                # permitted" — on which rootd exits. The socket at
                # /run/hop3-rootd/socket never appeared and EVERY deploy failed
                # at proxy reload, which also goes through rootd.
                #
                # The container is standing in for a server that manages its own
                # firewall, so it needs the capability that implies. Without it,
                # apps declaring fixed ports (owncast, matrix-synapse) can never
                # be tested here at all.
                "--cap-add=NET_ADMIN",
                "--name",
                self.container_name,
                # Who owns this container. A run that is killed cannot clean up
                # after itself — SIGKILL leaves no chance to — so the next run
                # has to be able to tell an abandoned container from one a live
                # run is using. The pid is that signal; see _reclaim_orphans.
                "--label",
                f"{OWNER_LABEL}={os.getpid()}",
                "--label",
                f"{OWNER_HOST_LABEL}={socket.gethostname()}",
                "--label",
                f"{MARKER_LABEL}=1",
                "-v",
                f"{DOWNLOAD_CACHE_VOLUME}:{DOWNLOAD_CACHE_PATH}",
                *(f"--publish={port}" for port in PUBLISHED_PORTS),
                self.image,
                "sleep",
                "infinity",
            ],
            capture_output=True,
            text=True,
            check=False,
        )

        if run_result.returncode != 0:
            print("  ✗ Failed to start container")
            if run_result.stderr:
                print(f"  Error: {run_result.stderr.strip()}")
            return False
        return True

    def _wait_for_container_ready(self, timeout_seconds: int = 15) -> bool:
        """
        Wait for container to be running.

        Args:
            timeout_seconds: Maximum time to wait.

        Returns:
            True if container is ready, False if timeout.
        """
        for _ in range(timeout_seconds * 2):  # Check every 0.5s
            if self._container_running():
                return True
            time.sleep(0.5)

        print("  ✗ Container failed to start within timeout")
        return False

    def setup(self) -> bool:
        """
        Start Docker container for deployment.

        This method:
        1. Builds the Docker image using docker build (with layer caching)
        2. Starts a container from the built image

        Docker's layer caching means subsequent builds are fast if
        the Dockerfile hasn't changed.
        """
        if reason := self._docker_unavailable_reason():
            print(f"  ✗ Docker is not available: {reason}")
            return False
        print(f"  → Docker daemon: {pin_docker_endpoint().url}")

        # Reuse a running container unless --clean was asked for: a second
        # deploy then hits the in-place UPDATE path (upgrade) instead of a
        # fresh install. --clean (or no running container) forces a rebuild.
        if self._container_running() and not self.config.clean_before:
            running = self._running_image()
            if running and running != self.image:
                # Reusing a container built from a different base silently
                # installs onto the wrong distribution, and the mismatch only
                # surfaces much later as a confusing package failure.
                print(
                    f"  → Container {self.container_name} runs {running}, "
                    f"but {self.image} was requested — recreating"
                )
                return self._create_fresh_container()
            print(f"  → Reusing running container {self.container_name} (no --clean)")
            return True

        return self._create_fresh_container()

    def _create_fresh_container(self) -> bool:
        """Drop any existing container and start a clean one."""
        self._remove_container()
        # An abandoned container of ours is ours to clear; a live one is not.
        self._reclaim_orphans()

        # A failed build stops the deploy. It used to fall back to a bare
        # ubuntu:24.04 with a few apt packages: a different machine from the
        # one the e2e image describes, announced by one printed line.
        if not self._build_image():
            return False

        if not self._start_container():
            return False

        if not self._wait_for_container_ready():
            return False

        print("  ✓ Container ready (packages pre-installed via cached layers)")
        return True

    def teardown(self) -> None:
        """Stop and remove the container."""
        subprocess.run(
            ["docker", "rm", "-f", self.container_name],
            capture_output=True,
            check=False,
        )

    def run(
        self,
        command: str,
        *,
        check: bool = True,
        stdin: str | None = None,
    ) -> CommandResult:
        """Run a command in the container."""
        docker_cmd = [
            "docker",
            "exec",
            *(["-i"] if stdin is not None else []),
            self.container_name,
            "bash",
            "-c",
            command,
        ]

        result = subprocess.run(
            docker_cmd,
            input=stdin,
            capture_output=True,
            text=True,
            check=False,
        )

        cmd_result = CommandResult.from_subprocess(result)
        self._raise_if_failed(cmd_result, command, check=check)
        return cmd_result

    def run_streaming(
        self, command: str, *, quiet: bool = False, log_file: Path | None = None
    ) -> int:
        """Run a command with output handling based on mode."""
        docker_cmd = [
            "docker",
            "exec",
            "-e",
            "PYTHONUNBUFFERED=1",
            "-e",
            "DEBIAN_FRONTEND=noninteractive",
            self.container_name,
            "bash",
            "-c",
            command,
        ]

        if quiet:
            # Capture output for log file
            result = subprocess.run(
                docker_cmd, capture_output=True, text=True, check=False
            )
            if log_file:
                self._write_log_output(
                    log_file, command, result.returncode, result.stdout, result.stderr
                )
            return result.returncode

        # Stream directly to terminal
        result = subprocess.run(docker_cmd, check=False)  # type: ignore[assignment]
        return result.returncode

    def upload_file(self, local_path: Path, remote_path: str) -> bool:
        """Copy a file into the container."""
        result = subprocess.run(
            ["docker", "cp", str(local_path), f"{self.container_name}:{remote_path}"],
            capture_output=True,
            check=False,
        )
        return result.returncode == 0

    def upload_dir(self, local_path: Path, remote_path: str) -> bool:
        """Copy a directory into the container, replacing what was there."""
        # `docker cp SRC CONTAINER:DEST` copies SRC *into* DEST when DEST is an
        # existing directory. On the update path DEST is always there from the
        # previous upload, so the new tree landed at DEST/<basename> and `pip
        # install DEST` reinstalled the old tree, with a green message and the
        # old version still running. Replace, never merge.
        if not self.run(f"rm -rf {shlex.quote(remote_path)}", check=False).success:
            return False
        result = subprocess.run(
            ["docker", "cp", str(local_path), f"{self.container_name}:{remote_path}"],
            capture_output=True,
            check=False,
        )
        if result.returncode == 0:
            # Fix permissions
            self.run(f"chmod -R a+rX {remote_path}", check=False)
        return result.returncode == 0

    def clean(self) -> None:
        """
        Clean the container for fresh installation.

        No addon storage to reclaim here, unlike the SSH backend: `--clean`
        forces `_create_fresh_container()`, so MySQL/PostgreSQL/Redis and their
        data are destroyed with the container itself. This is belt and braces on
        a container that is about to be replaced.
        """
        commands = [
            "systemctl stop hop3-server 2>/dev/null || true",
            "rm -rf /home/hop3",
            "userdel -r hop3 2>/dev/null || true",
            "groupdel hop3 2>/dev/null || true",
        ]

        for cmd in commands:
            self.run(cmd, check=False)

    def get_server_url(self) -> str:
        """Get the URL to access the server."""
        host = pin_docker_endpoint().published_host
        return f"http://{host}:{self.published_port(API_PORT)}"

    def published_port(self, container_port: int) -> int:
        """The host port Docker picked for one of the container's ports."""
        result = subprocess.run(
            ["docker", "port", self.container_name, f"{container_port}/tcp"],
            capture_output=True,
            text=True,
            check=False,
        )
        # One line per address family: "0.0.0.0:32768", "[::]:32768".
        lines = result.stdout.split()
        if result.returncode != 0 or not lines:
            msg = (
                f"Container {self.container_name} publishes no port "
                f"{container_port}: {result.stderr.strip() or 'no mapping'}"
            )
            raise RuntimeError(msg)
        return int(lines[0].rpartition(":")[2])

    def get_container_ip(self) -> str | None:
        """Get the container's internal IP address."""
        result = subprocess.run(
            [
                "docker",
                "inspect",
                "-f",
                "{{range .NetworkSettings.Networks}}{{.IPAddress}}{{end}}",
                self.container_name,
            ],
            capture_output=True,
            text=True,
            check=False,
        )
        if result.returncode == 0:
            return result.stdout.strip()
        return None

    def service_restart_command(self, service: str) -> str:
        """
        Supervisor manages services in the container — there is no systemd.

        The upgrade path restarts hop3-server here; using ``systemctl`` would
        silently no-op (systemctl can't run without a systemd PID 1), leaving
        the old code serving while the deploy reports success.
        """
        return f"supervisorctl restart {service}"

    def service_logs_command(self, service: str) -> str:
        """Supervisor keeps the logs here; there is no journal in a container."""
        return f"supervisorctl tail -100 {service}"

    def start_services(self) -> None:
        """
        Start supervisor to manage services after Hop3 installation.

        This replaces systemd in Docker environments. Supervisor manages:
        - sshd: SSH server
        - nginx: Reverse proxy
        - uwsgi-hop3: Application processes (emperor mode)
        - hop3-server: Hop3 API server

        Raises:
            ServiceStartError: If services fail to start.
        """
        print("  → Setting up supervisor to manage services...")

        # Docker creates the volume's mountpoint root-owned, but builds run as
        # hop3 — so hand it over before anything tries to write a download there.
        # Non-recursive: existing entries were written by this same uid on an
        # earlier run. `mkdir -p` first: a container created by a pre-0.7
        # deployer (the upgrade chain's first hop) has no cache volume mounted
        # here, and the update path used to die on the chown with "No such file
        # or directory". Without the volume the cache simply lives in the
        # container, which is what a test box wants anyway.
        self.run(
            f"mkdir -p {DOWNLOAD_CACHE_PATH} && chown hop3:hop3 {DOWNLOAD_CACHE_PATH}"
        )

        # Write supervisor config
        config_cmd = (
            f"cat > /etc/supervisor/conf.d/hop3.conf << 'EOF'\n{SUPERVISOR_CONFIG}EOF"
        )
        result = self.run(config_cmd, check=False)
        if not result.success:
            msg = "Failed to write supervisor config"
            print(f"  ✗ {msg}")
            raise ServiceStartError(msg)

        # Check if supervisord is already running
        result = self.run("pgrep -x supervisord", check=False)
        if result.success:
            # Supervisord is running, just reload config
            print("  → Reloading supervisor config...")
            result = self.run(
                "supervisorctl reread && supervisorctl update", check=False
            )
        else:
            # Start supervisord in background. It daemonizes (the config sets no
            # `nodaemon`), so this returns and the container keeps its own
            # long-running process as PID 1.
            #
            # There used to be a `pkill -f 'sleep infinity'` here, to "kill the
            # sleep process that's keeping the container alive". It never did:
            # `sleep infinity` WAS pid 1, and the kernel discards a signal sent
            # to pid 1 when pid 1 installed no handler for it. Under `--init`
            # tini is pid 1 and the sleep is an ordinary child, so the same line
            # would kill it for real — and tini exits when its child does,
            # taking the container down in the middle of its own deploy.
            print("  → Starting supervisord...")
            result = self.run(
                "supervisord -c /etc/supervisor/supervisord.conf",
                check=False,
            )

        if not result.success:
            msg = "Failed to start supervisor"
            print(f"  ✗ {msg}")
            raise ServiceStartError(msg)

        # Wait for services to start
        print("  → Waiting for services to start...")
        time.sleep(3)

        # Verify services are running
        result = self.run("supervisorctl status", check=False)
        if result.success:
            running_count = result.stdout.count("RUNNING")
            print(f"  ✓ Supervisor started ({running_count} services running)")
        else:
            print("  ⚠ Supervisor started but some services may have issues")
