"""
Docker deployment backend for local containers.

Trust model
-----------
This module is loaded *only* by ``hop3-deploy``, the developer-facing
deploy tool used to spin up a throwaway Docker container for local
testing and CI. It is **never** imported by ``hop3-install`` (the
production server installer).

The hardcoded ``E2E_TEST_SECRET_KEY`` below is the supervisor's
*fallback* JWT signing key, used only when the installer hasn't written
``/etc/hop3/secret-key`` (which the server reads first, and which the
installer normally generates). The harness never signs with it: it
fetches a token from the container with ``hop3-server admin:ssh-token``
(``DockerTarget._fetch_api_token``), which signs with whatever key the
server validates with. The container is ephemeral, but its ports are
published on every interface of the daemon's machine, so
its API answers that machine's network while it runs: keep the Docker host on
a trusted network. If this module is ever loaded in a context where
``MODE=production``, that is a bug; we abort at backend construction time
rather than risk shipping the test key into a real deploy.
"""

from __future__ import annotations

import os
import shlex
import socket
import subprocess
import time
from pathlib import Path
from typing import TYPE_CHECKING

from hop3_installer.common import CommandResult, ServiceStartError
from hop3_installer.deployer.docker_endpoint import pin_docker_endpoint

from .base import DeployBackend

if TYPE_CHECKING:
    from hop3_installer.deployer.config import DeployConfig

# E2E test secret key - must match hop3-testing/src/hop3_testing/targets/constants.py
# DO NOT change this string and DO NOT reuse it outside the developer
# Docker deploy backend; see the trust-model note at the top of the file.
E2E_TEST_SECRET_KEY = "e2e-test-secret-key-do-not-use-in-production"

# Where `hop3-fetch` keeps downloaded build inputs inside the container, and the
# named volume that backs it. On a real server the cache lives under the hop3
# home and persists by itself; here the container is thrown away between runs,
# so without a volume every catalog run re-downloads every tarball — which is
# what got this address rate-limited by GitHub in the first place.
#
# A named volume, not a bind mount: it survives `docker rm`, and `chown` works
# on it (a macOS bind mount presents its own ownership, so the hop3 user could
# not write there). Clear it with `docker volume rm hop3-download-cache`.
DOWNLOAD_CACHE_VOLUME = "hop3-download-cache"
DOWNLOAD_CACHE_PATH = "/var/cache/hop3-downloads"

# Labels stamped on every container this backend creates, so a later run can
# recognise one of ours and find out whether anybody still owns it.
MARKER_LABEL = "hop3.test.container"
OWNER_LABEL = "hop3.test.owner-pid"
#: The machine that pid lives on: the daemon may serve several.
OWNER_HOST_LABEL = "hop3.test.owner-host"

#: The container ports a deploy publishes, each on a host port Docker picks: a
#: fixed host port collides with whatever else the Docker host runs (LocalAI
#: holds 8080 on a typical build box).
API_PORT = 8000
PUBLISHED_PORTS = (API_PORT, 80, 443)

