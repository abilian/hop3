def main() -> int:
    """Main entry point. Returns exit code."""
    parser = create_parser()
    args = parser.parse_args()

    # Header
    print_header("Hop3 Server Installer")

    # Check root
    if os.geteuid() != 0:
        print_error("This installer must be run as root")
        print_detail("Use: sudo python3 install-server.py")
        return 1

    # Detect distro
    distro = detect_distro()
    print_info(f"Detected distribution: {distro}")

    total_steps = 12

    # Show configuration
    if args.domain:
        print_info(f"Domain: {args.domain} (will request Let's Encrypt certificate)")
    else:
        print_info("No domain specified (will use self-signed certificate)")

    # Step 1: System dependencies
    print_step(1, total_steps, "Installing system dependencies...")
    try:
        install_system_deps(distro, args.skip_deps)
    except CommandError as e:
        print_error(f"Failed to install dependencies: {e.stderr[:200]}")
        return 1

    # Step 2: Create user
    print_step(2, total_steps, "Creating hop3 user and group...")
    try:
        create_user_and_group()
    except CommandError as e:
        print_error(f"Failed to create user: {e.stderr}")
        return 1

    # Step 3: Virtual environment
    print_step(3, total_steps, "Creating virtual environment...")
    try:
        create_virtual_environment()
    except CommandError as e:
        print_error(f"Failed to create venv: {e.stderr}")
        return 1

    # Step 4: Install package
    print_step(4, total_steps, "Installing hop3-server...")
    try:
        install_package(
            version=args.version,
            use_git=args.git,
            branch=args.branch,
            local_path=args.local_path,
            verbose=args.verbose,
        )
    except CommandError as e:
        print_error("Failed to install hop3-server")
        if args.verbose:
            print_detail(e.stderr[:500])
        return 1

    # Step 5: Run setup
    print_step(5, total_steps, "Running initial setup...")
    try:
        run_hop3_setup()
    except CommandError as e:
        print_error(f"Setup failed: {e.stderr[:200]}")
        return 1

    # Step 6: SSH keys
    print_step(6, total_steps, "Configuring SSH keys...")
    setup_ssh_keys()

    # Step 7: Systemd
    print_step(7, total_steps, "Setting up systemd services...")
    try:
        setup_systemd()
    except CommandError as e:
        print_warning(f"Systemd setup issue: {e.stderr[:100]}")

    # Step 8: SSL certificates (self-signed first, Let's Encrypt later if domain provided)
    print_step(8, total_steps, "Setting up SSL certificates...")
    try:
        setup_ssl_selfsigned()
    except CommandError as e:
        print_warning(f"SSL setup issue: {e.stderr[:100]}")

    # Step 9: Nginx (needs SSL cert first)
    print_step(9, total_steps, "Configuring nginx reverse proxy...")
    try:
        setup_nginx(args.skip_nginx, args.domain)
    except CommandError as e:
        print_warning(f"Nginx setup issue: {e.stderr[:100]}")

    # Step 10: PostgreSQL
    print_step(10, total_steps, "Configuring PostgreSQL...")
    pg_password = None
    try:
        pg_password = setup_postgres(args.skip_postgres, distro)
    except CommandError as e:
        print_warning(f"PostgreSQL setup issue: {e.stderr[:100]}")

    # Step 11: Write server configuration
    print_step(11, total_steps, "Writing server configuration...")
    try:
        write_server_config(pg_password)
    except Exception as e:
        print_warning(f"Config write issue: {e}")

    # Step 12: ACME/Let's Encrypt
    print_step(12, total_steps, "Setting up ACME/Let's Encrypt...")
    try:
        # Always install acme.sh for future use
        setup_acme(args.skip_acme)

        # If domain provided, request Let's Encrypt certificate
        if args.domain and not args.skip_acme:
            if setup_letsencrypt(args.domain):
                # Reload nginx to use the new certificate
                run_cmd(["systemctl", "reload", "nginx"], check=False)
                print_success("Nginx reloaded with Let's Encrypt certificate")
    except CommandError as e:
        print_warning(f"ACME setup issue: {e.stderr[:100]}")

    # Verify
    print()
    verify_installation()

    # Success
    print_final_message(args.domain)

    return 0


if __name__ == "__main__":
    try:
        sys.exit(main())
    except KeyboardInterrupt:
        print("\n\nInstallation cancelled.")
        sys.exit(130)
    except Exception as e:
        print(f"\n{Colors.RED}Error:{Colors.RESET} {e}", file=sys.stderr)
        sys.exit(1)
