def detect_distro() -> str:
    """Detect the Linux distribution. Returns 'debian', 'fedora', or 'unknown'."""
    os_release = Path("/etc/os-release")
    if os_release.exists():
        content = os_release.read_text()
        if any(d in content.lower() for d in ["ubuntu", "debian", "mint", "pop"]):
            return "debian"
        if any(
            d in content.lower() for d in ["fedora", "rhel", "centos", "rocky", "alma"]
        ):
            return "fedora"
        if "arch" in content.lower():
            return "arch"
    return "unknown"


def user_exists(username: str) -> bool:
    """Check if a user exists."""
    try:
        pwd.getpwnam(username)
        return True
    except KeyError:
        return False


def group_exists(groupname: str) -> bool:
    """Check if a group exists."""
    try:
        grp.getgrnam(groupname)
        return True
    except KeyError:
        return False


