@dataclass
class ServerInstallerConfig:
    """Configuration for server installer."""

    # Installation source
    version: str | None = None
    use_git: bool = False
    branch: str = DEFAULT_BRANCH
    local_path: str | None = None

    # Installation options
    force: bool = False
    skip_deps: bool = False
    skip_nginx: bool = False
    skip_postgres: bool = False
    skip_acme: bool = False
    domain: str | None = None
    verbose: bool = False

    # Optional features
    features: set[str] = field(default_factory=set)

    @property
    def with_mysql(self) -> bool:
        return "mysql" in self.features

    @property
    def with_redis(self) -> bool:
        return "redis" in self.features

    @property
    def with_docker(self) -> bool:
        return "docker" in self.features

    @classmethod
    def from_env(cls) -> ServerInstallerConfig:
        """Create config from environment variables."""
        features_str = os.environ.get("HOP3_WITH", "")
        features = parse_features(features_str)

        return cls(
            version=os.environ.get("HOP3_VERSION"),
            use_git=os.environ.get("HOP3_GIT", "").lower() in ("1", "true"),
            branch=os.environ.get("HOP3_BRANCH", DEFAULT_BRANCH),
            local_path=os.environ.get("HOP3_LOCAL_PACKAGE"),
            force=os.environ.get("HOP3_FORCE", "").lower() in ("1", "true"),
            skip_deps=os.environ.get("HOP3_SKIP_DEPS", "").lower() in ("1", "true"),
            skip_nginx=os.environ.get("HOP3_SKIP_NGINX", "").lower() in ("1", "true"),
            skip_postgres=os.environ.get("HOP3_SKIP_POSTGRES", "").lower()
            in ("1", "true"),
            skip_acme=os.environ.get("HOP3_SKIP_ACME", "").lower() in ("1", "true"),
            domain=os.environ.get("HOP3_DOMAIN"),
            verbose=os.environ.get("HOP3_VERBOSE", "").lower() in ("1", "true"),
            features=features,
        )


def parse_features(features_str: str) -> set[str]:
    """Parse comma-separated feature list.

    Args:
        features_str: Comma-separated features (e.g., "mysql,redis" or "all")

    Returns:
        Set of feature names to install
    """
    if not features_str:
        return set()

    features_str = features_str.lower().strip()

    # Handle "all" keyword
    if features_str == "all":
        return ALL_FEATURES.copy()

    # Parse comma-separated list
    features = set()
    for feature in features_str.split(","):
        feature = feature.strip()
        if feature == "all":
            features.update(ALL_FEATURES)
        elif feature in ALL_FEATURES:
            features.add(feature)
        elif feature == "postgres":
            # PostgreSQL is always installed by default, ignore
            pass
        elif feature:
            # Unknown feature - will be warned about in main
            pass

    return features


