def setup_ssh_keys() -> None:
    """Copy root SSH keys to hop3 user if available."""
    root_keys = Path("/root/.ssh/authorized_keys")

    if not root_keys.exists():
        print_info("No root SSH keys found, skipping")
        return

    content = root_keys.read_text().strip()
    if not content:
        print_info("Root SSH keys file is empty, skipping")
        return

    hop_server = f"{VENV_DIR}/bin/hop-server"
    temp_keys = Path("/tmp/root_authorized_keys")

    try:
        # Copy keys to temp location
        shutil.copy2(root_keys, temp_keys)
        hop3_uid = pwd.getpwnam(HOP3_USER).pw_uid
        hop3_gid = grp.getgrnam(HOP3_GROUP).gr_gid
        os.chown(temp_keys, hop3_uid, hop3_gid)

        # Run setup:ssh
        run_as_hop3(f"{hop_server} setup:ssh {temp_keys}")
        print_success("SSH keys configured")
    except CommandError:
        print_warning("Could not configure SSH keys (invalid format?)")
    finally:
        if temp_keys.exists():
            temp_keys.unlink()


def setup_systemd() -> None:
    """Install and enable systemd services."""
    # Hop3 server service
    service_path = Path("/etc/systemd/system/hop3-server.service")
    service_path.write_text(SYSTEMD_UNIT)

    # uWSGI service
    uwsgi_path = Path("/etc/systemd/system/uwsgi-hop3.service")
    uwsgi_path.write_text(UWSGI_UNIT)

    # Reload and enable
    run_cmd(["systemctl", "daemon-reload"])
    run_cmd(["systemctl", "enable", "hop3-server"], check=False)
    run_cmd(["systemctl", "enable", "uwsgi-hop3"], check=False)
    run_cmd(["systemctl", "start", "hop3-server"], check=False)

    print_success("Systemd services configured")


def setup_nginx(skip: bool, domain: str | None = None) -> None:
    """Configure nginx as reverse proxy for hop3-server."""
    if skip:
        print_info("Skipping nginx setup (--skip-nginx)")
        return

    # Determine server name
    server_name = domain if domain else "_"

    # Generate nginx config
    nginx_config = NGINX_CONFIG.format(
        server_name=server_name,
        ssl_cert=str(SSL_CERT),
        ssl_key=str(SSL_KEY),
    )

    # Write config file
    nginx_config_path = Path("/etc/nginx/sites-available/hop3")
    nginx_enabled_path = Path("/etc/nginx/sites-enabled/hop3")

    # For Fedora/RHEL, use conf.d instead
    if not Path("/etc/nginx/sites-available").exists():
        nginx_config_path = Path("/etc/nginx/conf.d/hop3.conf")
        nginx_enabled_path = None  # No symlink needed

    nginx_config_path.parent.mkdir(parents=True, exist_ok=True)
    nginx_config_path.write_text(nginx_config)
    print_success(f"Nginx config written to {nginx_config_path}")

    # Create symlink if using sites-available/sites-enabled
    if nginx_enabled_path:
        nginx_enabled_path.parent.mkdir(parents=True, exist_ok=True)
        if nginx_enabled_path.exists() or nginx_enabled_path.is_symlink():
            nginx_enabled_path.unlink()
        nginx_enabled_path.symlink_to(nginx_config_path)
        print_success("Nginx site enabled")

        # Remove default site if exists
        default_site = Path("/etc/nginx/sites-enabled/default")
        if default_site.exists() or default_site.is_symlink():
            default_site.unlink()
            print_info("Removed default nginx site")

    # Add include for app-specific nginx configs in /home/hop3/nginx/
    _add_hop3_nginx_include()

    # Test nginx config
    try:
        run_cmd(["nginx", "-t"])
        print_success("Nginx configuration is valid")
    except CommandError as e:
        print_error(f"Nginx configuration test failed: {e.stderr[:200]}")
        return

    # Enable and start/reload nginx
    run_cmd(["systemctl", "enable", "nginx"], check=False)
    run_cmd(["systemctl", "restart", "nginx"], check=False)
    print_success("Nginx enabled and started")


def _add_hop3_nginx_include() -> None:
    """Add include directive for hop3 app configs to nginx.conf."""
    nginx_conf = Path("/etc/nginx/nginx.conf")
    include_line = "include /home/hop3/nginx/*.conf;"

    if not nginx_conf.exists():
        print_warning("nginx.conf not found, skipping app include setup")
        return

    content = nginx_conf.read_text()

    # Check if already present
    if include_line in content:
        print_info("Hop3 app nginx include already configured")
        return

    # Create the nginx directory for app configs
    hop3_nginx_dir = HOME_DIR / "nginx"
    hop3_nginx_dir.mkdir(parents=True, exist_ok=True)
    hop3_uid = pwd.getpwnam(HOP3_USER).pw_uid
    hop3_gid = grp.getgrnam(HOP3_GROUP).gr_gid
    os.chown(hop3_nginx_dir, hop3_uid, hop3_gid)

    # Find the right place to add the include (after sites-enabled or conf.d include)
    # Look for existing include patterns in the http block
    lines = content.split("\n")
    new_lines = []
    include_added = False

    for i, line in enumerate(lines):
        new_lines.append(line)
        # Add after sites-enabled or conf.d include
        if not include_added and "include" in line:
            if "sites-enabled" in line or "conf.d" in line:
                # Preserve indentation
                indent = len(line) - len(line.lstrip())
                new_lines.append(" " * indent + include_line)
                include_added = True

    if include_added:
        nginx_conf.write_text("\n".join(new_lines))
        print_success("Added hop3 app nginx include to nginx.conf")
    else:
        print_warning("Could not find suitable location for nginx include")


def setup_postgres(skip: bool, distro: str) -> str | None:
    """Configure PostgreSQL.

    Returns:
        The generated postgres superuser password, or None if skipped.
    """
    if skip:
        print_info("Skipping PostgreSQL setup (--skip-postgres)")
        return None

    # Initialize PostgreSQL on Fedora
    if distro == "fedora":
        if not Path("/var/lib/pgsql/data/pg_hba.conf").exists():
            run_cmd(["postgresql-setup", "--initdb"], check=False)

    run_cmd(["systemctl", "enable", "postgresql"], check=False)
    run_cmd(["systemctl", "start", "postgresql"], check=False)

    # Create role and database for hop3 user
    try:
        run_cmd(
            ["su", "-", "postgres", "-c", f"createuser --createdb {HOP3_USER}"],
            check=False,
        )
        run_cmd(
            ["su", "-", "postgres", "-c", f"createdb -O {HOP3_USER} hop3"],
            check=False,
        )
        print_success("PostgreSQL role and database created")
    except CommandError:
        print_info("PostgreSQL role/database may already exist")

    # Set a password for the postgres superuser
    # This is needed for hop3-server to create addon databases via TCP connection
    pg_password = "hop3_" + secrets.token_hex(16)

    # Use psql to set the password (peer auth works since we're root -> postgres user)
    sql_cmd = f"ALTER USER postgres PASSWORD '{pg_password}';"
    result = run_cmd(
        ["su", "-", "postgres", "-c", f'psql -c "{sql_cmd}"'],
        check=False,
    )
    if result.returncode == 0:
        print_success("PostgreSQL superuser password configured")
    else:
        print_warning("Could not set PostgreSQL superuser password")
        return None

    # Configure PostgreSQL to accept connections from Docker containers
    # Docker containers connect via host.docker.internal which routes to 172.17.x.x
    _configure_postgres_for_docker(distro)

    return pg_password


def _configure_postgres_for_docker(distro: str) -> None:
    """Configure PostgreSQL to accept connections from Docker containers.

    This modifies postgresql.conf and pg_hba.conf to:
    1. Listen on all interfaces (not just localhost)
    2. Allow password auth from Docker bridge network (172.17.0.0/16)
    """
    # Find PostgreSQL config directory
    if distro == "fedora":
        pg_conf_dir = Path("/var/lib/pgsql/data")
    else:  # debian
        # Find the postgresql version directory
        pg_dirs = list(Path("/etc/postgresql").glob("*/main"))
        if not pg_dirs:
            print_warning("Could not find PostgreSQL config directory")
            return
        pg_conf_dir = pg_dirs[0]

    pg_conf = pg_conf_dir / "postgresql.conf"
    pg_hba = pg_conf_dir / "pg_hba.conf"

    if not pg_conf.exists():
        print_warning(f"PostgreSQL config not found at {pg_conf}")
        return

    # Update listen_addresses to accept connections from Docker
    conf_content = pg_conf.read_text()
    if "listen_addresses = '*'" not in conf_content:
        # Comment out existing listen_addresses and add new one
        new_lines = []
        for line in conf_content.split("\n"):
            if line.strip().startswith("listen_addresses"):
                new_lines.append(f"# {line}  # commented by hop3 installer")
            else:
                new_lines.append(line)
        new_lines.append("")
        new_lines.append("# Added by hop3 installer for Docker container access")
        new_lines.append("listen_addresses = '*'")
        pg_conf.write_text("\n".join(new_lines))
        print_success("PostgreSQL configured to listen on all interfaces")

    # Add pg_hba.conf rule for Docker networks
    # 172.16.0.0/12 covers all Docker networks (172.16.x.x - 172.31.x.x)
    # including default bridge (172.17.x.x) and docker-compose networks (172.18+)
    hba_content = pg_hba.read_text()
    docker_rule = "host    all    all    172.16.0.0/12    scram-sha-256"
    if "172.16.0.0/12" not in hba_content:
        # Add rule before the first "host" line (after local rules)
        new_lines = []
        docker_rule_added = False
        for line in hba_content.split("\n"):
            # Add Docker rule before first host rule
            if not docker_rule_added and line.strip().startswith("host"):
                new_lines.append(
                    "# Added by hop3 installer for Docker container access"
                )
                new_lines.append(docker_rule)
                new_lines.append("")
                docker_rule_added = True
            new_lines.append(line)
        # If no host rules found, add at end
        if not docker_rule_added:
            new_lines.append("")
            new_lines.append("# Added by hop3 installer for Docker container access")
            new_lines.append(docker_rule)
        pg_hba.write_text("\n".join(new_lines))
        print_success("PostgreSQL configured to accept Docker container connections")

    # Restart PostgreSQL to apply changes
    run_cmd(["systemctl", "restart", "postgresql"], check=False)
    print_success("PostgreSQL restarted with new configuration")


def write_server_config(pg_password: str | None) -> None:
    """Write hop3-server.toml configuration file.

    This configures hop3-server with:
    - PostgreSQL connection settings (host, password)
    """
    config_file = HOME_DIR / "hop3-server.toml"

    # Build config content
    lines = [
        "# Hop3 Server Configuration",
        "# Auto-generated by installer",
        "",
    ]

    if pg_password:
        lines.extend(
            [
                "# PostgreSQL admin connection settings",
                "# Use 127.0.0.1 (TCP) instead of localhost (Unix socket) for password auth",
                'POSTGRES_HOST = "127.0.0.1"',
                f'POSTGRES_SUPERUSER_PASSWORD = "{pg_password}"',
                "",
            ]
        )

    config_file.write_text("\n".join(lines))

    # Set ownership to hop3 user
    hop3_uid = pwd.getpwnam(HOP3_USER).pw_uid
    hop3_gid = grp.getgrnam(HOP3_GROUP).gr_gid
    os.chown(config_file, hop3_uid, hop3_gid)
    os.chmod(config_file, 0o600)  # Secure - contains password

    print_success(f"Server configuration written to {config_file}")


def setup_acme(skip: bool) -> None:
    """Install acme.sh for Let's Encrypt."""
    if skip:
        print_info("Skipping ACME setup (--skip-acme)")
        return

    acme_sh = HOME_DIR / ".acme.sh" / "acme.sh"

    if acme_sh.exists():
        print_info("acme.sh already installed")
        return

    with Spinner("Installing acme.sh..."):
        # Download
        run_as_hop3(
            "curl -fsSL https://raw.githubusercontent.com/Neilpang/acme.sh/master/acme.sh -o /tmp/acme.sh"
        )
        # Install (must run from /tmp)
        run_as_hop3("cd /tmp && bash acme.sh --install")
        run_cmd(["rm", "-f", "/tmp/acme.sh"])

    # Set default CA
    if acme_sh.exists():
        run_as_hop3(f"bash {acme_sh} --set-default-ca --server letsencrypt")
        print_success("acme.sh installed and configured")
    else:
        print_warning("acme.sh installation may have failed")


def setup_ssl_selfsigned() -> None:
    """Generate a self-signed SSL certificate for hop3-server."""
    if SSL_CERT.exists() and SSL_KEY.exists():
        print_info("SSL certificates already exist")
        return

    # Create SSL directory
    SSL_DIR.mkdir(parents=True, exist_ok=True)

    with Spinner("Generating self-signed SSL certificate..."):
        # Generate self-signed certificate valid for 10 years
        run_cmd(
            [
                "openssl",
                "req",
                "-x509",
                "-nodes",
                "-days",
                "3650",
                "-newkey",
                "rsa:2048",
                "-keyout",
                str(SSL_KEY),
                "-out",
                str(SSL_CERT),
                "-subj",
                "/CN=hop3-server/O=Hop3/C=US",
                "-addext",
                "subjectAltName=DNS:localhost,IP:127.0.0.1",
            ]
        )

    # Set permissions
    os.chmod(SSL_KEY, 0o600)
    os.chmod(SSL_CERT, 0o644)

    print_success("Self-signed SSL certificate generated")
    print_detail(f"Certificate: {SSL_CERT}")
    print_detail(f"Private key: {SSL_KEY}")


def setup_letsencrypt(domain: str) -> bool:
    """Request a Let's Encrypt certificate using acme.sh."""
    acme_sh = HOME_DIR / ".acme.sh" / "acme.sh"

    if not acme_sh.exists():
        print_error("acme.sh not installed, cannot request Let's Encrypt certificate")
        return False

    # Create webroot directory
    webroot = Path("/var/www/html")
    webroot.mkdir(parents=True, exist_ok=True)

    print_info(f"Requesting Let's Encrypt certificate for {domain}...")

    with Spinner("Requesting certificate (this may take a minute)..."):
        try:
            # Issue certificate using webroot mode
            run_as_hop3(
                f"bash {acme_sh} --issue -d {domain} -w {webroot} --keylength 2048"
            )
        except CommandError as e:
            print_error(f"Failed to request certificate: {e.stderr[:200]}")
            return False

    # Install certificate to hop3 SSL directory
    SSL_DIR.mkdir(parents=True, exist_ok=True)

    try:
        run_as_hop3(
            f"bash {acme_sh} --install-cert -d {domain} "
            f"--key-file {SSL_KEY} "
            f"--fullchain-file {SSL_CERT} "
            f"--reloadcmd 'sudo systemctl reload nginx'"
        )
    except CommandError as e:
        print_error(f"Failed to install certificate: {e.stderr[:200]}")
        return False

    # Set permissions
    os.chmod(SSL_KEY, 0o600)
    os.chmod(SSL_CERT, 0o644)

    print_success(f"Let's Encrypt certificate installed for {domain}")
    return True


def verify_installation() -> bool:
    """Verify the installation."""
    hop_server = VENV_DIR / "bin" / "hop-server"

    if not hop_server.exists():
        print_error("hop-server not found")
        return False

    # Check hop3-server service status
    result = run_cmd(
        ["systemctl", "is-active", "hop3-server"], capture=True, check=False
    )
    if result.stdout.strip() == "active":
        print_success("hop3-server service is running")
    else:
        print_warning("hop3-server service is not running")
        print_detail("Check with: sudo systemctl status hop3-server")

    # Check nginx service status
    result = run_cmd(["systemctl", "is-active", "nginx"], capture=True, check=False)
    if result.stdout.strip() == "active":
        print_success("nginx service is running")
    else:
        print_warning("nginx service is not running")
        print_detail("Check with: sudo systemctl status nginx")

    # Check SSL certificate exists
    if SSL_CERT.exists() and SSL_KEY.exists():
        print_success("SSL certificate is configured")
    else:
        print_warning("SSL certificate not found")

    return True


